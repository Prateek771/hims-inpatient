// Merges T1/T2/T3 trigger blocks into ../0004_triggers.sql in PostgreSQL firing order.
// PostgreSQL fires same-table/timing/event triggers alphabetically by name; MariaDB fires them in creation order.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const header = /^-- TRIGGER name=(\S+) table=(\S+) timing=(BEFORE|AFTER) event=(INSERT|UPDATE|DELETE) pg_name=(\S+)\s*$/;
const blocks = [];

for (const group of ["T1", "T2", "T3", "T4", "T5"]) {
  let current = null;
  for (const line of readFileSync(join(dir, `${group}.sql`), "utf8").split(/\r?\n/)) {
    const m = header.exec(line);
    if (m) {
      current = { group, name: m[1], table: m[2], timing: m[3], event: m[4], pg: m[5], body: [] };
    } else if (line.trim() === "-- END TRIGGER") {
      if (!current) throw new Error(`${group}: END without header`);
      blocks.push(current);
      current = null;
    } else if (current) {
      current.body.push(line);
    }
  }
  if (current) throw new Error(`${group}: unterminated block ${current.name}`);
}

const names = new Set();
for (const b of blocks) {
  if (names.has(b.name)) throw new Error(`duplicate trigger name ${b.name}`);
  names.add(b.name);
  if (b.body.join("\n").includes("$$")) throw new Error(`${b.name} contains $$`);
}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
blocks.sort((a, b) => cmp(a.table, b.table) || cmp(a.timing, b.timing) || cmp(a.event, b.event) || cmp(a.pg, b.pg) || cmp(a.name, b.name));

const out = ["-- Generated by triggers/merge.mjs from T1/T2/T3.sql; do not edit by hand.", "DELIMITER $$"];
for (const b of blocks) {
  out.push(`-- ${b.name} (${b.table} ${b.timing} ${b.event}; pg ${b.pg}; ${b.group})`);
  const stmts = b.body.join("\n").split(/;\s*\n(?=\s*CREATE\b)/i); // DROP line, then CREATE
  if (stmts.length !== 2) throw new Error(`${b.name}: expected DROP + CREATE`);
  out.push(`${stmts[0].trim().replace(/;$/, "")}$$`);
  out.push(`${stmts[1].trim().replace(/;$/, "")}$$`);
}
out.push("DELIMITER ;", "");

writeFileSync(join(dir, "..", "0004_triggers.sql"), out.join("\n"));

// The readiness check requires exactly these triggers to exist.
const triggerNames = blocks.map((b) => b.name).sort();
writeFileSync(
  join(dir, "..", "..", "src", "server", "expected-triggers.ts"),
  `// Generated by drizzle-maria/triggers/merge.mjs; do not edit by hand.\nexport const expectedTriggers: readonly string[] = ${JSON.stringify(triggerNames, null, 2)};\n`,
);
console.log(`merged ${blocks.length} triggers`);
