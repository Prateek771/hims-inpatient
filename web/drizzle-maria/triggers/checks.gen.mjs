// Extracts the commit-time rule queries (blocks tagged "-- T2-CHECK <name>") from docs/agent/MARIADB_PORT_GAPS.md
// into src/server/deferred-check-queries.ts. Each query uses `<ids>` as the placeholder for the touched row ids.
//   node triggers/checks.gen.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const docs = readFileSync(join(dir, "..", "..", "..", "docs", "agent", "MARIADB_PORT_GAPS.md"), "utf8");
const queries = {};
for (const block of docs.matchAll(/```sql\n-- T2-CHECK (\w+)\n([\s\S]*?)```/g)) queries[block[1]] = block[2].trim();
const expected = ["closed_receipt", "external_charge_pair", "transfer_effects"];
for (const name of expected) if (!queries[name]) throw new Error(`missing T2-CHECK ${name}`);
const out = [
  "// Generated by drizzle-maria/triggers/checks.gen.mjs from docs/agent/MARIADB_PORT_GAPS.md; do not edit by hand.",
  "// Commit-time rules PostgreSQL enforced with DEFERRABLE constraint triggers. `<ids>` is replaced by the touched row ids.",
  `export const deferredCheckQueries = ${JSON.stringify(queries, null, 2)} as const;`,
  "",
].join("\n");
writeFileSync(join(dir, "..", "..", "src", "server", "deferred-check-queries.ts"), out);
console.log(`extracted ${Object.keys(queries).length} queries`);
