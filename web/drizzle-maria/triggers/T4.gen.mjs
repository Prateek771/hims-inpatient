// Generates T4.sql: append-only guards that PostgreSQL enforced with runtime-role grants (no UPDATE/DELETE) and
// that a single MariaDB user cannot enforce by privilege. Needs a database with 0001-0004 applied:
//   DATABASE_URL=mysql://... node triggers/T4.gen.mjs   (then: node triggers/merge.mjs)
// Rules mirror the former runtime grants: full-update tables, column-limited tables and delete-allowed tables below.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createConnection } from "mysql2/promise";

const dir = dirname(fileURLToPath(import.meta.url));
const fullUpdate = new Set(["hospital_settings", "staff_user", "staff_account", "staff_session", "staff_verification", "beds", "admissions", "admission_counters"]);
const columnLimited = {
  room_stays: ["ended_at", "last_reconciled_at", "posted_paise"],
  care_billing_events: ["tariff_version_id", "resolution_reason", "state"],
  pharmacy_batches: ["available_quantity"],
  insurance_cases: ["assigned_staff_id", "version", "review_revision", "document_set_revision"],
  paperwork_runs: ["status", "revision", "pending_review_id"],
};
const deletable = new Set(["staff_session", "staff_verification", "bed_holds"]);
const internal = /^(hims_locks|hims_migrations|lg_.*)$/; // helper and checkpointer tables are mutable by design

const url = new URL(process.env.DATABASE_URL ?? "");
const connection = await createConnection({ host: url.hostname, port: Number(url.port) || 3306, user: decodeURIComponent(url.username), password: decodeURIComponent(url.password), database: url.pathname.slice(1) });
const [tables] = await connection.query("SELECT TABLE_NAME AS name FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME");
const [columns] = await connection.query("SELECT TABLE_NAME AS t, COLUMN_NAME AS c FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE() ORDER BY TABLE_NAME, ORDINAL_POSITION");
const [existing] = await connection.query("SELECT EVENT_OBJECT_TABLE AS t, EVENT_MANIPULATION AS e FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = DATABASE() AND ACTION_TIMING = 'BEFORE' AND TRIGGER_NAME NOT LIKE 'append_only\\_%'");
await connection.end();

const covered = new Set(existing.map((r) => `${r.t}:${r.e}`));
const columnsOf = (table) => columns.filter((r) => r.t === table).map((r) => r.c);
const blocks = [];
const block = (name, table, event, pgName, body) =>
  blocks.push(`-- TRIGGER name=${name} table=${table} timing=BEFORE event=${event} pg_name=${pgName}\nDROP TRIGGER IF EXISTS ${name};\nCREATE TRIGGER ${name} BEFORE ${event} ON ${table} FOR EACH ROW\nBEGIN\n  -- The dedicated test owner account (absent on the hosting database) may prepare fixtures, as the former table owner could.\n  IF USER() NOT LIKE 'hims_test_owner@%' THEN\n${body}\n  END IF;\nEND\n-- END TRIGGER`);
const refuse = (message) => `  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '${message}';`;

for (const { name: table } of tables) {
  if (internal.test(table)) continue;
  if (!deletable.has(table) && !covered.has(`${table}:DELETE`)) {
    block(`append_only_${table}_del`, table, "DELETE", "00_append_only_del", refuse(`${table} records are append-only; record a linked correction instead`));
  }
  if (columnLimited[table]) {
    const frozen = columnsOf(table).filter((c) => !columnLimited[table].includes(c));
    const same = frozen.map((c) => `NEW.\`${c}\` <=> OLD.\`${c}\``).join("\n    AND ");
    block(`append_only_${table}_cols`, table, "UPDATE", "00_append_only_cols", `  IF NOT (${same}) THEN\n  ${refuse(`Only ${columnLimited[table].join(", ")} may change on ${table}; record a linked correction instead`)}\n  END IF;`);
  } else if (!fullUpdate.has(table) && !covered.has(`${table}:UPDATE`)) {
    block(`append_only_${table}_upd`, table, "UPDATE", "00_append_only_upd", refuse(`${table} records are append-only; record a linked correction instead`));
  }
}
writeFileSync(join(dir, "T4.sql"), `-- Generated by T4.gen.mjs; append-only guards replacing the former runtime-role grants.\n${blocks.join("\n")}\n`);
console.log(`T4: ${blocks.length} triggers`);
